#  How to create variables in Python? 

# In Python, a variable is created when you assign a value to it using the = operator.You do not need to declare the data type.

# 1. Basic Variable Creation

x = 10
name = "Kaif"
price = 99.5


# x → integer
# name → string
# price → float


# 2. Printing Variables

x = 10
print(x)

# Output:
# 10


# 3. Multiple Variables in One Line

a, b, c = 1, 2, 3
print(a, b, c)


# 4. Rules for Variable Names

# Must start with a letter or _
# Cannot start with a number
# Cannot use keywords
# Case-sensitive (name and Name are different)

# Example:

student_name = "XYZ"