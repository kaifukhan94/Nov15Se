# Write a Python program to demonstrate the creation of variables and different data types. 

# Creating variables with different data types

# Integer
age = 20

# Float
price = 99.50

# String
name = "Kaif"

# List
numbers = [1, 2, 3, 4]

# Tuple
colors = ("red", "green", "blue")

# Dictionary
student = {"name": "Kaif", "age": 20}

# Set
unique_numbers = {1, 2, 3, 4}

# Printing the variables
print("Integer:", age)
print("Float:", price)
print("String:", name)
print("List:", numbers)
print("Tuple:", colors)
print("Dictionary:", student)
print("Set:", unique_numbers)

# Checking types
print(type(age))
print(type(price))
print(type(name))
print(type(numbers))
print(type(colors))
print(type(student))
print(type(unique_numbers))