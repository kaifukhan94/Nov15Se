# How does the Python code structure work? 

# Python code is written in a simple and organized way so that the interpreter can understand and execute it.

# 1. Statements
# A program is made up of statements (instructions).

# Example:

x = 10
print(x)



# 2. Indentation (Very Important)
# Python uses indentation (spaces) to define blocks of code.

# Example:

if x > 5:
    print("Greater than 5")

# 👉 No { } like other languages — indentation is the structure.



# 3. Comments
# Comments are used to explain the code.

# This is a comment
print("Hello")



# 4. Variables and Data
# Variables store values.

name = "Kaif"
age = 20



# 5. Control Structures
# Used to control flow of the program.

# Conditions
if age >= 18:
    print("Adult")

# Loops
for i in range(3):
    print(i)



# 6. Functions
# Functions are reusable blocks of code.

def greet():
    print("Hello")

greet()



# 7. Execution Flow
# Python executes code line by line from top to bottom.