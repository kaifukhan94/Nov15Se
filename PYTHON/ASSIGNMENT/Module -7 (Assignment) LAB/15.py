# 15) Write a Python program to access alternate values between index 1 and 5 in a tuple.  


# Creating a tuple
my_tuple = (10, 20, 30, 40, 50, 60, 70)

# Accessing alternate elements from index 1 to 5 (excluding 5)
alternate_values = my_tuple[1:5:2]

# Display the result
print("Alternate values from index 1 to 4:", alternate_values)